const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('archiver', Object.freeze({
  state: () => ipcRenderer.invoke('state'),
  chooseLocation: () => ipcRenderer.invoke('choose-location'),
  wipeAllData: () => ipcRenderer.invoke('wipe-all-data'),
  openLogs: () => ipcRenderer.invoke('open-logs'),
  signIn: () => ipcRenderer.invoke('sign-in'),
  synchronize: () => ipcRenderer.invoke('synchronize'),
  resyncProduct: id => ipcRenderer.invoke('resync-product', id),
  skipError: id => ipcRenderer.invoke('skip-error', id),
  pause: () => ipcRenderer.invoke('pause'),
  openFile: (productId, fileId) => ipcRenderer.invoke('open-file', productId, fileId),
  beginPack: () => ipcRenderer.invoke('begin-pack'),
  pickPackFiles: cover => ipcRenderer.invoke('pick-pack-files', cover),
  createPack: fields => ipcRenderer.invoke('create-pack', fields),
  deletePack: id => ipcRenderer.invoke('delete-pack', id),
  diskFiles: id => ipcRenderer.invoke('disk-files', id),
  revealDiskFile: (id, relative) => ipcRenderer.invoke('reveal-disk-file', id, relative),
  openPackDirectory: id => ipcRenderer.invoke('open-pack-directory', id),
  openLink: url => ipcRenderer.invoke('open-link', url),
  organize: change => ipcRenderer.invoke('organize', change),
  details: id => ipcRenderer.invoke('details', id),
  onState: callback => { const listener = (_event, state) => callback(state); ipcRenderer.on('state', listener); return () => ipcRenderer.removeListener('state', listener); },
}));
